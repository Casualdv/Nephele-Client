enum NetMsg {
    Chunks(Vec<ChunkColumn>),
    Unload(i32, i32),
    Chat(String),
    /// The full entity table, replaced wholesale. Cheap enough at 20 Hz.
    Entities(Vec<EntitySnapshot>),
    /// Tab-list skin hashes (uuid, texture hash).
    Skins(Vec<([u8; 16], String)>),
    Error(String),
}

/// One tracked entity, copied out of the client so the render thread can
/// interpolate it without touching the network thread's state.
#[derive(Debug, Clone, Copy)]
struct EntitySnapshot {
    player: bool,
    uuid: [u8; 16],
    /// Interpolation start and latest server position.
    prev: [f64; 3],
    position: [f64; 3],
    prev_yaw: f32,
    yaw: f32,
    head_yaw: f32,
    prev_head_yaw: f32,
    pitch: f32,
    /// Mob type, used to tint non-player entities.
    kind: u8,
}

impl EntitySnapshot {
    fn from_entity(entity: &nephele_client::Entity) -> Self {
        let (player, uuid, kind) = match &entity.kind {
            nephele_client::EntityKind::Player { uuid, .. } => (true, *uuid, 0),
            nephele_client::EntityKind::Mob { kind } => (false, [0; 16], *kind),
        };
        Self {
            player,
            uuid,
            prev: entity.prev,
            position: entity.position,
            prev_yaw: entity.prev_yaw,
            yaw: entity.yaw,
            head_yaw: entity.head_yaw,
            prev_head_yaw: entity.prev_head_yaw,
            pitch: entity.pitch,
            kind,
        }
    }
}

struct Shared {
    player: PlayerState,
    yaw: f32,
    pitch: f32,
    input: Input,
    teleport: Option<[f64; 3]>,
    status: String,
    spawned: bool,
    error: Option<String>,
    /// Left mouse button held.
    attacking: bool,
    /// Right click queued; the network thread consumes and clears it.
    use_pressed: bool,
    /// Hotbar slot the player just selected.
    pending_slot: Option<i16>,
    /// Written by the network thread, read by the renderer.
    aim: Option<Aim>,
    break_stage: Option<u8>,
    held_slot: i16,
    creative: bool,
    /// Mirror of the 45-slot player container, for the hotbar.
    inventory: Vec<Option<ItemStack>>,
    health: f32,
    food: i32,
    xp_bar: f32,
    xp_level: i32,
    chunks: usize,
    /// Requested by the creative inventory, applied by the network thread.
    give_item: Option<(i16, ItemStack)>,
    /// Render distance, pushed to the server as a client-settings update.
    view_distance: u8,
    /// Position at the start of the current tick, and when that tick began, so
    /// the renderer can interpolate between 20 Hz physics ticks.
    prev_position: [f64; 3],
    tick_at: Instant,
}

pub fn run(options: PlayOptions) -> Result<(), Box<dyn Error>> {
    let shared = Arc::new(Mutex::new(Shared {
        player: PlayerState::default(),
        yaw: 0.0,
        pitch: 0.0,
        input: Input::default(),
        teleport: None,
        status: String::new(),
        spawned: false,
        error: None,
        attacking: false,
        use_pressed: false,
        pending_slot: None,
        aim: None,
        break_stage: None,
        held_slot: 0,
        creative: false,
        inventory: vec![None; 45],
        health: 20.0,
        food: 20,
        xp_bar: 0.0,
        xp_level: 0,
        chunks: 0,
        give_item: None,
        view_distance: nephele_client::VIEW_DISTANCE,
        prev_position: [0.5, 80.0, 0.5],
        tick_at: Instant::now(),
    }));

    let (tx, rx) = mpsc::channel::<NetMsg>();

    let event_loop = EventLoop::new()?;
    event_loop.set_control_flow(ControlFlow::Poll);
    let mut app = LiveApp::new(options, shared, rx, tx);
    event_loop.run_app(&mut app)?;
    match app.error.take() {
        Some(err) => Err(err),
        None => Ok(()),
    }
}

/// One 20 Hz simulation step, shared by the network and single-player loops.
fn step_player(shared: &Arc<Mutex<Shared>>, world: &World) -> (Vec3, f32, f32, bool) {
    let mut state = shared.lock().unwrap();
    if let Some([x, y, z]) = state.teleport.take() {
        state.player.teleport(x, y, z);
    }
    state.prev_position = [state.player.x, state.player.y, state.player.z];
    let input = state.input;
    let yaw = state.yaw;
    state.player.step(TICK.as_secs_f64(), &input, yaw, world);
    state.tick_at = Instant::now();
    (
        Vec3::new(state.player.x, state.player.y, state.player.z),
        state.yaw,
        state.pitch,
        state.player.on_ground,
    )
}

/// Single-player: generate terrain around the player, simulate, and let them
/// mine and place without a server.
fn local_loop(seed: u64, shared: Arc<Mutex<Shared>>, tx: Sender<NetMsg>) -> Result<(), String> {
    use nephele_protocol::packets::play::HOTBAR_FIRST_SLOT;
    use nephele_world::{BlockState, ChunkCoord, TerrainGenerator};

    let generator = TerrainGenerator::new(seed);
    let mut world = World::new(0);
    // Honour the render-distance setting; `radius` is re-read every tick so
    // changing it in Options takes effect without restarting the world.
    let mut radius;

    let mut inventory = [None; 9];
    for (index, block) in nephele_client::STARTER_HOTBAR.iter().enumerate() {
        inventory[index] = Some(ItemStack::new(block.id() as i16, 64, block.meta() as i16));
    }

    {
        let mut state = shared.lock().unwrap();
        let spawn_y = generator.spawn_height() as f64;
        state.player.teleport(0.5, spawn_y, 0.5);
        state.spawned = true;
        state.creative = true;
        state.status = format!("Singleplayer (seed {seed})");
        for (index, item) in inventory.iter().enumerate() {
            state.inventory[HOTBAR_FIRST_SLOT + index] = *item;
        }
    }

    let mut sent: HashSet<(i32, i32)> = HashSet::new();
    let mut miner = Miner::default();

    loop {
        let (position, yaw, pitch, _on_ground) = step_player(&shared, &world);
        radius = view_radius(shared.lock().unwrap().view_distance);

        // Stream generated columns around the player.
        let centre = (
            (position.x / 16.0).floor() as i32,
            (position.z / 16.0).floor() as i32,
        );
        let mut columns = Vec::new();
        for dx in -radius..=radius {
            for dz in -radius..=radius {
                let coord = (centre.0 + dx, centre.1 + dz);
                if !sent.insert(coord) {
                    continue;
                }
                let column = generator.column(coord.0, coord.1);
                world.insert(column.clone());
                columns.push(column);
            }
        }
        let stale: Vec<(i32, i32)> = sent
            .iter()
            .copied()
            .filter(|(x, z)| (x - centre.0).abs() > radius + 2 || (z - centre.1).abs() > radius + 2)
            .collect();
        for coord in stale {
            sent.remove(&coord);
            world.remove(ChunkCoord::new(coord.0, coord.1));
            let _ = tx.send(NetMsg::Unload(coord.0, coord.1));
        }
        if !columns.is_empty() {
            let _ = tx.send(NetMsg::Chunks(columns));
        }

        // What are we looking at?
        let eye = [position.x, position.y + EYE_HEIGHT, position.z];
        let direction = look_direction(yaw, pitch);
        let aim = raycast(&world, eye, direction, REACH_CREATIVE).map(|hit| Aim {
            x: hit.x,
            y: hit.y,
            z: hit.z,
            face: hit.face.protocol_id(),
            cursor: [
                (hit.point[0] - hit.x as f64).clamp(0.0, 1.0) as f32,
                (hit.point[1] - hit.y as f64).clamp(0.0, 1.0) as f32,
                (hit.point[2] - hit.z as f64).clamp(0.0, 1.0) as f32,
            ],
        });

        let (attacking, use_pressed, pending_slot, give) = {
            let mut state = shared.lock().unwrap();
            (
                state.attacking,
                std::mem::take(&mut state.use_pressed),
                state.pending_slot.take(),
                state.give_item.take(),
            )
        };
        if let Some(slot) = pending_slot {
            shared.lock().unwrap().held_slot = slot;
        }
        if let Some((slot, item)) = give {
            let hotbar = (slot as usize).saturating_sub(HOTBAR_FIRST_SLOT);
            if hotbar < inventory.len() {
                inventory[hotbar] = Some(item);
            }
            let mut state = shared.lock().unwrap();
            if let Some(entry) = state.inventory.get_mut(slot as usize) {
                *entry = Some(item);
            }
        }

        let mut dirty: HashSet<(i32, i32)> = HashSet::new();
        for event in miner.tick(&world, aim, attacking, true) {
            if let MiningEvent::Stop(target) = event {
                world.set_block(target.x, target.y, target.z, BlockState::AIR);
                dirty.insert((target.x.div_euclid(16), target.z.div_euclid(16)));
            }
        }
        if use_pressed {
            if let Some(aim) = aim {
                let held = {
                    let state = shared.lock().unwrap();
                    state
                        .inventory
                        .get(HOTBAR_FIRST_SLOT + state.held_slot.max(0) as usize)
                        .copied()
                        .flatten()
                };
                if let Some(state_block) = held.and_then(|item| item.block_state()) {
                    let normal = nephele_world::Face::from_protocol_id(aim.face)
                        .map(|face| face.normal())
                        .unwrap_or([0, 1, 0]);
                    let (bx, by, bz) = (aim.x + normal[0], aim.y + normal[1], aim.z + normal[2]);
                    if world.get_block(bx, by, bz).is_air() {
                        world.set_block(bx, by, bz, BlockState::from_raw(state_block));
                        dirty.insert((bx.div_euclid(16), bz.div_euclid(16)));
                    }
                }
            }
        }
        for (cx, cz) in dirty {
            if let Some(column) = world.get(ChunkCoord::new(cx, cz)) {
                let _ = tx.send(NetMsg::Chunks(vec![column.clone()]));
            }
        }

        {
            let mut state = shared.lock().unwrap();
            state.aim = aim;
            state.break_stage = miner.stage();
            state.chunks = world.loaded_chunks();
        }

        std::thread::sleep(TICK);
    }
}

/// Camera-relative look vector, matching [`Camera::forward`].
fn look_direction(yaw: f32, pitch: f32) -> [f64; 3] {
    let (sin_yaw, cos_yaw) = yaw.sin_cos();
    let (sin_pitch, cos_pitch) = pitch.sin_cos();
    [
        (sin_yaw * cos_pitch) as f64,
        sin_pitch as f64,
        (-cos_yaw * cos_pitch) as f64,
    ]
}

async fn net_loop(
    address: ServerAddress,
    username: String,
    shared: Arc<Mutex<Shared>>,
    tx: Sender<NetMsg>,
) -> Result<(), String> {
    let mut client = GameClient::join(&address, &username)
        .await
        .map_err(|err| err.to_string())?;

    let creative = client.is_creative();
    if creative {
        if let Err(err) = client.give_starter_hotbar().await {
            eprintln!("could not fill the creative hotbar: {err}");
        }
    }
    {
        let mut state = shared.lock().unwrap();
        state.status = format!("{} @ {}", client.info.username, address);
        state.creative = creative;
    }

    let mut miner = Miner::default();
    let mut world_dirty = false;
    let mut sent_view_distance = shared.lock().unwrap().view_distance;

    // Chunks we've already handed to the renderer. Diffing against the world
    // each tick catches bulk loads, which only report their last column.
    let mut sent: HashSet<(i32, i32)> = HashSet::new();
    let mut ticker = tokio::time::interval(TICK);
    ticker.set_missed_tick_behavior(tokio::time::MissedTickBehavior::Delay);

    loop {
        tokio::select! {
            _ = ticker.tick() => {
                let (position, yaw, pitch, on_ground) = step_player(&shared, &client.world);
                let (attacking, use_pressed, pending_slot, give) = {
                    let mut state = shared.lock().unwrap();
                    (
                        state.attacking,
                        std::mem::take(&mut state.use_pressed),
                        state.pending_slot.take(),
                        state.give_item.take(),
                    )
                };

                let requested_view_distance = shared.lock().unwrap().view_distance;
                if requested_view_distance != sent_view_distance {
                    client
                        .send_client_settings(requested_view_distance)
                        .await
                        .map_err(|err| err.to_string())?;
                    sent_view_distance = requested_view_distance;
                }

                if let Some(slot) = pending_slot {
                    client
                        .set_held_slot(slot)
                        .await
                        .map_err(|err| err.to_string())?;
                }

                if let Some((slot, item)) = give {
                    client
                        .creative_set_slot(slot, Some(item))
                        .await
                        .map_err(|err| err.to_string())?;
                }

                // What are we looking at?
                let eye = [position.x, position.y + EYE_HEIGHT, position.z];
                let direction = look_direction(yaw, pitch);
                let reach = if creative { REACH_CREATIVE } else { REACH_SURVIVAL };
                let aim = raycast(&client.world, eye, direction, reach).map(|hit| Aim {
                    x: hit.x,
                    y: hit.y,
                    z: hit.z,
                    face: hit.face.protocol_id(),
                    cursor: [
                        (hit.point[0] - hit.x as f64).clamp(0.0, 1.0) as f32,
                        (hit.point[1] - hit.y as f64).clamp(0.0, 1.0) as f32,
                        (hit.point[2] - hit.z as f64).clamp(0.0, 1.0) as f32,
                    ],
                });

                for event in miner.tick(&client.world, aim, attacking, creative) {
                    match event {
                        MiningEvent::Start(target) => {
                            client.dig(digging::START_DESTROY_BLOCK, &target).await
                                .map_err(|err| err.to_string())?;
                            client.swing().await.map_err(|err| err.to_string())?;
                        }
                        MiningEvent::Stop(target) => {
                            client.dig(digging::STOP_DESTROY_BLOCK, &target).await
                                .map_err(|err| err.to_string())?;
                        }
                        MiningEvent::Abort(target) => {
                            client.dig(digging::ABORT_DESTROY_BLOCK, &target).await
                                .map_err(|err| err.to_string())?;
                        }
                    }
                }

                if use_pressed {
                    if let Some(target) = aim {
                        client.place(&target).await.map_err(|err| err.to_string())?;
                    }
                }

                client
                    .send_move(position, yaw, pitch, on_ground)
                    .await
                    .map_err(|err| err.to_string())?;

                // One client tick: snapshot every entity's interpolation start,
                // then hand the whole table to the renderer.
                client.entities.tick();
                let snapshot: Vec<EntitySnapshot> = client
                    .entities
                    .iter()
                    .map(EntitySnapshot::from_entity)
                    .collect();
                let _ = tx.send(NetMsg::Entities(snapshot));

                {
                    let mut state = shared.lock().unwrap();
                    state.aim = aim;
                    state.break_stage = miner.stage();
                    state.held_slot = client.held_slot;
                    state.health = client.health;
                    state.food = client.food;
                    state.xp_bar = client.xp_bar;
                    state.xp_level = client.xp_level;
                    state.chunks = client.world.loaded_chunks();
                    if state.inventory.len() != client.inventory.len() {
                        state.inventory = client.inventory.clone();
                    } else {
                        state.inventory.copy_from_slice(&client.inventory);
                    }
                }

                let mut batch = Vec::new();
                for (coord, column) in client.world.iter() {
                    if !sent.contains(&(coord.x, coord.z)) {
                        batch.push(column.clone());
                    }
                }
                if world_dirty {
                    // A block changed somewhere: re-send what the renderer has
                    // so its copy of the world matches the server's.
                    world_dirty = false;
                    for (coord, column) in client.world.iter() {
                        if sent.contains(&(coord.x, coord.z)) {
                            batch.push(column.clone());
                        }
                    }
                }
                if !batch.is_empty() {
                    for column in &batch {
                        sent.insert((column.x, column.z));
                    }
                    let _ = tx.send(NetMsg::Chunks(batch));
                }

                let stale: Vec<(i32, i32)> = sent
                    .iter()
                    .copied()
                    .filter(|(x, z)| !client.world.contains(ChunkCoord::new(*x, *z)))
                    .collect();
                for (x, z) in stale {
                    sent.remove(&(x, z));
                    let _ = tx.send(NetMsg::Unload(x, z));
                }
            }
            event = client.tick(Duration::from_millis(100)) => {
                match event {
                    Ok(Event::Position { position, yaw, pitch }) => {
                        let mut state = shared.lock().unwrap();
                        state.teleport = Some([position.x, position.y, position.z]);
                        state.yaw = yaw;
                        state.pitch = pitch;
                        state.spawned = true;
                    }
                    Ok(Event::Chat(text)) => {
                        let _ = tx.send(NetMsg::Chat(text));
                    }
                    Ok(Event::BlocksChanged(_)) => {
                        world_dirty = true;
                    }
                    Ok(Event::PlayerList) => {
                        let skins: Vec<([u8; 16], String)> = client
                            .skins
                            .iter()
                            .filter_map(|(uuid, info)| {
                                info.hash.clone().map(|hash| (*uuid, hash))
                            })
                            .collect();
                        if !skins.is_empty() {
                            let _ = tx.send(NetMsg::Skins(skins));
                        }
                    }
                    Ok(_) => {}
                    Err(err) => return Err(err.to_string()),
                }
            }
        }
    }
}

